"""Render the results CSVs as markdown tables for docs/final_report.md (results/report_tables.md),
and the recall-precision figure (results/phase5_precision_recall_by_stratum.png).

Run after phases 1, 3 and 5: uv run python scripts/fusion/report_tables.py
"""

from __future__ import annotations

import json

import numpy as np
import pandas as pd

from ds_flood_gfm.fusion.config import load_config

STRATA = ["open_nosnow", "vegetated_nosnow", "urban_nosnow", "open_snow", "vegetated_snow", "urban_snow"]


def md(df: pd.DataFrame, floatfmt: str = "{:.3f}") -> str:
    def f(v):
        if isinstance(v, (float, np.floating)):
            return "" if np.isnan(v) else floatfmt.format(v)
        if isinstance(v, (int, np.integer)):
            return f"{v:,}"
        return str(v).replace("|", "\\|")  # e.g. "fusion|gfm": a bare pipe would split the table cell

    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(f(r[c]) for c in cols) + " |")
    return "\n".join(lines)


def with_rp(df: pd.DataFrame) -> pd.DataFrame:
    """Add recall = TP/(TP+FN) and precision = TP/(TP+FP), the scores the team reports; CSI stays for criterion (b)."""
    d = df.copy()
    d["recall"] = d.tp / (d.tp + d.fn)
    d["precision"] = d.tp / (d.tp + d.fp)
    return d


def main() -> None:
    cfg = load_config()
    res = cfg.results_dir
    out = ["# Report tables (generated by scripts/fusion/report_tables.py)\n"]
    gate = json.loads((res / "phase1_gate.json").read_text())
    out.append("## Phase 1 gate\n")
    oc, oa = gate["oracle_conditional"], gate["oracle_all_cells"]
    rows = pd.DataFrame([
        {"test": "oracle CSI (observed cells)", "best single": oc["best_overall_source"], "best single CSI": oc["best_overall"],
         "oracle CSI": oc["oracle"], "gain (points)": oc["gain_points"], "per-stratum gain (points)": oc["per_stratum_gain_points"]},
        {"test": "oracle CSI (all cells)", "best single": oa["best_overall_source"], "best single CSI": oa["best_overall"],
         "oracle CSI": oa["oracle"], "gain (points)": oa["gain_points"], "per-stratum gain (points)": oa["per_stratum_gain_points"]},
    ])
    out.append(md(rows, "{:.3f}"))
    c = gate["coverage"]
    out.append("\n\nCoverage of the floodable domain per window-day (training events): " + ", ".join(f"{k} {100 * v:.1f}%" for k, v in c.items()))
    out.append(f"\n\n3-day coverage gain over GFM alone: **{gate['coverage_gain_any3d_minus_gfm_pp']:.1f} pp** "
               f"(over GFM within 3 days: {gate['coverage_gain_any3d_minus_gfm3d_pp']:.1f} pp). Decision: **{gate['decision']}**.\n")
    sk = pd.read_csv(res / "phase1_skill_by_source_stratum.csv")
    sk = sk[sk.source.isin(["gfm", "microwave", "viirs", "floodscan", "gfds"])]
    out.append("\n## Phase 1 skill by source and stratum (training events, gold days, observed cells)\n")
    out.append(md(sk[["source", "stratum", "truth_flood", "obs_truth_flood", "sens", "pofd", "far", "csi", "csi_all", "coverage_flood",
                      "spec_incl_dry_windows"]].sort_values(["stratum", "source"])))
    s1 = pd.read_csv(res / "phase1_skill_by_label_s1.csv")
    out.append("\n\n### GFM circularity check (gold maps derived from Sentinel-1 vs other)\n")
    out.append(md(s1[s1.source == "gfm"][["label_s1", "truth_flood", "obs_truth_flood", "sens", "far", "csi"]]))
    acc = pd.read_csv(res / "accuracy_table.csv")
    out.append("\n\n## Accuracy table (results/accuracy_table.csv)\n")
    out.append(md(acc[["source", "stratum", "method", "sens", "sens_lo", "sens_hi", "spec", "spec_lo", "spec_hi", "n_flood_obs", "n_dry_obs",
                       "flag_wide_ci", "flag_small_n"]]))
    pw = pd.read_csv(res / "phase3_post_window_pofd.csv")
    out.append("\n\n### False-alarm rate by dry-window position (recession check)\n")
    out.append(md(pw.pivot(index="source", columns="bin", values="pofd").reset_index(), "{:.4f}"))
    pr = pd.read_csv(res / "prior_v1.csv")
    out.append("\n\n## Prior v1 (results/prior_v1.csv)\n")
    out.append(md(pr, "{:.5f}"))
    ov = with_rp(pd.read_csv(res / "phase5_skill_overall.csv"))
    ovf = ov[ov.model == "full"]
    out.append("\n\n## Phase 5: held-out skill, all strata (recall, precision; CSI for criterion b)\n")
    out.append("`all` = every gold cell, a source's NoData counts as a miss; `conditional` = only the cells that source observed "
               "(fusion|x = fusion scored on x's observed cells).\n")
    out.append(md(ovf[["product", "mode", "truth_flood", "tp", "fp", "fn", "recall", "precision", "csi"]].sort_values(["mode", "product"])))
    st = with_rp(pd.read_csv(res / "phase5_skill_by_stratum.csv"))
    full = st[(st.model == "full") & (st["mode"] == "all") & st["product"].isin(["fusion", "gfm", "microwave", "viirs", "floodscan", "gfds"])]
    out.append("\n\n## Phase 5: held-out skill by stratum (all cells; a source's NoData = not detected)\n")
    out.append(md(full[["stratum", "product", "truth_flood", "tp", "fp", "fn", "recall", "precision", "csi"]].sort_values(["stratum", "product"])))
    cond = st[(st.model == "full") & (st["mode"] == "conditional")]
    out.append("\n\n## Phase 5: held-out skill on each source's observed cells (fusion scored on the same cells)\n")
    out.append(md(cond[["stratum", "product", "truth_flood", "tp", "fp", "fn", "recall", "precision", "csi"]].sort_values(["stratum", "product"])))
    ct = with_rp(pd.read_csv(res / "phase5_skill_by_continent.csv"))
    ctf = ct[(ct.model == "full") & (ct["mode"] == "all") & ct["product"].isin(["fusion", "gfm", "microwave", "viirs"])]
    out.append("\n\n## Phase 5: held-out skill by continent (all cells)\n")
    out.append(md(ctf[["continent", "product", "truth_flood", "recall", "precision", "csi"]].sort_values(["continent", "product"])))
    crit = pd.read_csv(res / "phase5_criteria.csv")
    out.append("\n\n## Phase 5: the three criteria by stratum\n")
    out.append(md(crit))
    rel = pd.read_csv(res / "phase5_reliability_summary.csv")
    out.append("\n\n## Reliability (held-out, gold days + dry windows)\n")
    out.append(md(rel))
    cov = pd.read_csv(res / "phase5_coverage_summary.csv")
    out.append("\n\n## Coverage of the floodable domain (held-out windows, all days)\n")
    out.append(md(cov))
    age = pd.read_csv(res / "phase5_obs_age_on_gold_days.csv")
    out.append(f"\n\nDays since last observation on gold days: median of window medians {age.age_median.median():.1f}, "
               f"median of window 90th percentiles {age.age_p90.median():.1f}; cells never observed in the window: "
               f"{age.never_observed.sum():,} of {age.n_domain.sum():,} cell-days.\n")
    tim = pd.read_csv(res / "phase5_timing.csv")
    lag_cols = [c for c in tim.columns if c.endswith("_lag_days")]
    any_cols = [c for c in tim.columns if c.endswith("_first_any_days")]
    t = pd.DataFrame({"product": [c.replace("_lag_days", "") for c in lag_cols],
                      "windows detected (on/after start)": [int(tim[c].notna().sum()) for c in lag_cols],
                      "median lag days": [tim[c].median() for c in lag_cols],
                      "windows detected (any time)": [int(tim[c].notna().sum()) for c in any_cols],
                      "median first-any days": [tim[c].median() for c in any_cols]})
    out.append(f"\n## Days from event start to first detection ({int((tim.gold_flood_footprint_cells > 0).sum())} held-out windows with gold flood)\n")
    out.append(md(t, "{:.1f}"))
    abl = with_rp(pd.read_csv(res / "phase5_ablation.csv"))
    out.append("\n\n## Ablation (held-out, all strata, fusion product, all cells)\n")
    out.append(md(abl[["model", "tp", "fp", "fn", "recall", "precision", "csi"]]))
    rc = pd.read_csv(res / "experiment_recalibration.csv")
    rc["precision"] = 1 - rc.far  # the experiment stores FAR = FP/(TP+FP); NaN where nothing was flagged
    out.append("\n\n## Recalibration experiment (held-out gold days; not the product)\n")
    out.append(md(rc[["stratum", "variant", "sens", "precision", "csi_gold_days", "reliability_slope_wls_quantile_bins",
                      "calibration_slope_logistic", "n_heldout_flood_gold"]].rename(columns={"sens": "recall"})))
    from ds_flood_gfm.fusion import plots

    plots.precision_recall_by_stratum(pd.read_csv(res / "phase5_skill_by_stratum.csv"), res / "phase5_precision_recall_by_stratum.png")
    (res / "report_tables.md").write_text("\n".join(out) + "\n")
    print(f"wrote {res / 'report_tables.md'}")


if __name__ == "__main__":
    main()
